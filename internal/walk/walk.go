// Package walk lists the source files that belong on the map.
package walk

import (
	"io/fs"
	"os"
	"path"
	"path/filepath"
	"regexp"
	"sort"
	"strings"

	"github.com/aidarbn/archmap/internal/gitstat"
)

// SkipDirs are directory names never descended into.
var SkipDirs = map[string]bool{
	"node_modules": true, "vendor": true, ".git": true, "dist": true, "build": true, ".next": true,
	"__pycache__": true, ".venv": true, "venv": true, "migrations": true, "Pods": true, ".gradle": true,
	"coverage": true, "DerivedData": true, "generated": true, "__generated__": true,
	"site-packages": true, "storybook-static": true,
}

// GeneratedSuffixes are file name suffixes of generated code.
var GeneratedSuffixes = []string{
	"_templ.go", ".pb.go", ".pb.gw.go", "_gen.go", ".gen.go", ".generated.ts",
	".generated.swift", ".d.ts", ".min.js", "_pb2.py", "_pb2_grpc.py", ".pb.swift",
}

var testRe = regexp.MustCompile(`(_test\.go|(^|/)test_[^/]*\.py|_test\.py|(^|/)tests?_[^/]*\.py|(^|/)tests\.py|\.(test|spec)\.[jt]sx?|Tests?\.(swift|kt))$|(^|/)(tests?|__tests__|e2e|androidTest|Tests|UITests)/`)

// IsTest reports whether p looks like a test file.
func IsTest(p string) bool { return testRe.MatchString(p) }

// PathOK reports whether the repo-relative slash path p should be analysed:
// supported extension, no skipped or hidden directory, not generated, and not a
// test unless withTests.
func PathOK(p string, exts map[string]bool, withTests bool) bool {
	if !exts[path.Ext(p)] {
		return false
	}
	parts := strings.Split(p, "/")
	for _, part := range parts[:len(parts)-1] {
		if SkipDirs[part] || strings.HasPrefix(part, ".") {
			return false
		}
	}
	for _, s := range GeneratedSuffixes {
		if strings.HasSuffix(p, s) {
			return false
		}
	}
	return withTests || !IsTest(p)
}

// IsGeneratedText reports whether the head of a file marks it as generated.
func IsGeneratedText(head string) bool {
	return (strings.Contains(head, "Code generated") && strings.Contains(head, "DO NOT EDIT")) ||
		strings.Contains(head, "@generated") || strings.Contains(head, "<auto-generated") ||
		strings.Contains(head, "Generated by the protocol buffer compiler")
}

// List returns the sorted, repo-relative (slash) paths of files to analyse.
// Inside a git repository the file set is tracked + untracked-not-ignored files;
// otherwise the tree is walked.
func List(root string, exts map[string]bool, withTests bool) []string {
	var paths []string
	if out, ok := gitstat.Git(root, "ls-files", "-z", "--cached", "--others", "--exclude-standard"); ok {
		for _, p := range strings.Split(out, "\x00") {
			if p != "" {
				paths = append(paths, p)
			}
		}
	} else {
		_ = filepath.WalkDir(root, func(p string, d fs.DirEntry, err error) error {
			if err != nil {
				return nil
			}
			if d.IsDir() {
				if p != root && (SkipDirs[d.Name()] || strings.HasPrefix(d.Name(), ".")) {
					return filepath.SkipDir
				}
				return nil
			}
			if rel, err := filepath.Rel(root, p); err == nil {
				paths = append(paths, rel)
			}
			return nil
		})
	}
	seen := map[string]bool{}
	var res []string
	for _, p := range paths {
		p = filepath.ToSlash(p)
		if seen[p] || !PathOK(p, exts, withTests) {
			continue
		}
		full := filepath.Join(root, filepath.FromSlash(p))
		st, err := os.Stat(full)
		if err != nil || !st.Mode().IsRegular() {
			continue
		}
		head, err := readHead(full, 600)
		if err != nil || IsGeneratedText(head) {
			continue
		}
		seen[p] = true
		res = append(res, p)
	}
	sort.Strings(res)
	return res
}

func readHead(p string, n int) (string, error) {
	f, err := os.Open(p)
	if err != nil {
		return "", err
	}
	defer f.Close()
	buf := make([]byte, n)
	k, _ := f.Read(buf)
	return string(buf[:k]), nil
}
