func TestFileDoc(t *testing.T) {
	cases := []struct{ name, path, src, want string }{
		{"go package comment", "a/x.go", "// Copyright 2020 Foo.\n\n// Package x does things. It is small.\n//\n// More text.\npackage x\n", "Package x does things. It is small."},
		{"go comment detached from package", "a/x.go", "// Package x does things.\n\npackage x\n", ""},
		{"go build tag only", "a/x.go", "//go:build linux\n\npackage x\n", ""},
		{"python docstring", "a/__init__.py", "#!/usr/bin/env python\n\"\"\"Billing helpers for orders.\n\nLonger text.\n\"\"\"\nimport os\n", "Billing helpers for orders."},
		{"python single quotes", "a/m.py", "'''Parses the incoming feed. Works offline.'''\n", "Parses the incoming feed. Works offline."},
		{"python no docstring", "a/m.py", "import os\n\"\"\"Not first.\"\"\"\n", ""},
		{"jsdoc", "a/index.ts", "/**\n * Cart store with persistence.\n * @module cart\n */\nexport const a = 1\n", "Cart store with persistence."},
		{"js license then jsdoc", "a/index.js", "/* Copyright (c) Meta */\n/**\n * Router for the admin area.\n */\nconst a = 1\n", "Router for the admin area."},
		{"js eslint banner", "a/index.js", "/* eslint-disable */\nconst a = 1\n", ""},
		{"js section title", "a/x.tsx", "// ** MUI Imports\nimport a from 'a'\n", ""},
		{"rust inner doc", "a/lib.rs", "//! Fast line oriented search.\n//! Second line.\n\nuse a;\n", "Fast line oriented search. Second line."},
		{"rust block inner doc", "a/lib.rs", "/*!\nThis crate provides routines for parsing.\n*/\n", "This crate provides routines for parsing."},
		{"java package-info", "a/package-info.java", "/*\n * Copyright 2012 the original author\n */\n/**\n * Domain model of the clinic.\n */\npackage a;\n", "Domain model of the clinic."},
		{"swift xcode header", "a/A.swift", "//\n//  A.swift\n//  Proj\n//\n//  Created by Bob on 1/1/20.\n//\n\nimport UIKit\n", ""},
		{"kotlin header", "a/A.kt", "/** Screen with the order list and filters. */\npackage a\n", "Screen with the order list and filters."},
		{"ruby hash comments", "a/a.rb", "#!/usr/bin/env ruby\n# Sinatra based router for the app.\n\nclass A; end\n", "Sinatra based router for the app."},
		{"commented-out code", "a/x.tsx", "// import * as React from 'react';\n// const a = 1;\nexport {}\n", ""},
		{"generated", "a/x.ts", "// Code generated by foo. DO NOT EDIT.\nexport {}\n", ""},
	}
	for _, c := range cases {
		if got := FileDoc(c.path, []byte(c.src)); got != c.want {
			t.Errorf("%s: got %q, want %q", c.name, got, c.want)
		}
	}
}

func TestShorten(t *testing.T) {
	if got := Shorten("One sentence here. Two is also kept. Three is dropped."); got != "One sentence here. Two is also kept." {
		t.Errorf("two sentences: %q", got)
	}
	if got := Shorten("Uses e.g. a cache and more words. Next one."); got != "Uses e.g. a cache and more words. Next one." {
		t.Errorf("abbreviation: %q", got)
	}
	long := strings.Repeat("word ", 100)
	if got := Shorten(long); len(got) > MaxDoc || !strings.HasSuffix(got, "...") {
		t.Errorf("long: %d %q", len(got), got)
	}
}
