package lang

import (
	"path"
	"regexp"
	"strings"
	"unicode"
	"unicode/utf8"
)

// MaxDoc is the longest description (in bytes) FileDoc and Shorten return.
const MaxDoc = 300

// noiseRe matches licence, copyright, generated-code and linter banners.
var noiseRe = regexp.MustCompile(`(?i)copyright|spdx-|licensed under|all rights reserved|permission is hereby granted|do not edit|code generated|auto-?generated|@generated|eslint-|prettier-|tslint:|@ts-(nocheck|ignore|check)|istanbul|noinspection|created by |generated by|-\*-|coding[:=]|go:build|\+build|go:generate|jshint|jslint|pylint:|flake8|type:\s*ignore|important:|make sure|\btodo\b|\bfixme\b`)

// decoRe matches decorative runs such as "-----", "=====" or "*****".
var decoRe = regexp.MustCompile(`[-=*_~#]{3,}`)

// codeRe matches a first line that is source code rather than prose.
var codeRe = regexp.MustCompile(`^(import|export|const|let|var|function|class|return|require|use|def|from \S+ import|package|#include|<\?|\})\b|^(import|export)\W|[;{]$|=>|\);?$`)

// FileDoc returns the description found at the top of a source file: the Go
// package comment, a Python module docstring, or the header comment (JSDoc,
// `//!`, `///`, `/* */`, `//`, `#`) of other languages. Licences, copyright
// and generated-code banners are skipped. The result is at most MaxDoc bytes.
func FileDoc(p string, src []byte) string {
	ext := strings.ToLower(path.Ext(p))
	text := strings.TrimPrefix(string(src), "\xef\xbb\xbf")
	var blocks []string
	switch ext {
	case ".py", ".pyi":
		if d, ok := pyDocstring(text); ok {
			blocks = []string{d}
		} else {
			blocks = headerBlocks(text, true)
		}
	case ".go":
		for _, b := range goPackageBlocks(text) {
			if strings.HasPrefix(b, "Package ") || strings.HasPrefix(b, "Command ") {
				blocks = append(blocks, b)
			}
		}
	default:
		blocks = headerBlocks(text, hashComments(ext))
	}
	for _, b := range blocks {
		if d := Describe(b); d != "" {
			return d
		}
	}
	return ""
}

func hashComments(ext string) bool {
	switch ext {
	case ".rb", ".sh", ".bash", ".ex", ".exs", ".pl", ".py", ".pyi":
		return true
	}
	return false
}

// Describe cleans one raw comment or README block and returns its first 1-2
// sentences, or "" if it is a banner (licence, generated code, ...).
func Describe(raw string) string {
	if noiseRe.MatchString(raw) {
		return ""
	}
	var keep []string
	for _, l := range strings.Split(raw, "\n") {
		l = strings.TrimSpace(decoRe.ReplaceAllString(l, " "))
		l = strings.TrimLeft(l, "!*#-= ")
		if IsArchLine(l) {
			continue
		}
		if l == "" {
			if len(keep) > 0 {
				break // first paragraph only
			}
			continue
		}
		if strings.HasPrefix(l, "@") || strings.HasPrefix(l, "```") || strings.HasPrefix(l, ">>>") {
			if len(keep) > 0 {
				break
			}
			continue
		}
		keep = append(keep, l)
	}
	if len(keep) > 0 && codeRe.MatchString(keep[0]) { // commented-out code
		return ""
	}
	// a short first line without a full stop is a title ("Config", "MUI Imports")
	if len(keep) > 1 && len(strings.Fields(keep[0])) <= 3 && !strings.ContainsAny(keep[0], ".:!?") {
		keep = keep[1:]
	}
	d := Shorten(strings.Join(keep, " "))
	if len(strings.Fields(d)) < 4 {
		return ""
	}
	return d
}

// Shorten collapses whitespace and keeps the first sentences of s (at most two)
// while they fit into MaxDoc bytes. It returns "" when s is not prose.
func Shorten(s string) string {
	s = strings.Join(strings.Fields(s), " ")
	if !strings.ContainsFunc(s, unicode.IsLetter) || utf8.RuneCountInString(s) < 6 {
		return ""
	}
	rs := []rune(s)
	var sents []string
	start := 0
	for i := 0; i < len(rs); i++ {
		if rs[i] != '.' && rs[i] != '!' && rs[i] != '?' {
			continue
		}
		if i+1 == len(rs) {
			break
		}
		if rs[i+1] != ' ' || i+2 >= len(rs) {
			continue
		}
		n := rs[i+2]
		if !unicode.IsUpper(n) && n != '"' && n != '`' && !unicode.IsDigit(n) {
			continue
		}
		if rs[i] == '.' && abbrevBefore(rs[start:i]) {
			continue
		}
		sents = append(sents, string(rs[start:i+1]))
		start = i + 2
	}
	sents = append(sents, string(rs[start:]))
	out := ""
	for i, sn := range sents {
		if i == 2 {
			break
		}
		next := sn
		if out != "" {
			next = out + " " + sn
		}
		if len(next) > MaxDoc {
			break
		}
		out = next
	}
	if out == "" { // one very long sentence
		out = cut(sents[0], MaxDoc)
	}
	return out
}

func cut(s string, n int) string {
	if len(s) <= n {
		return s
	}
	s = s[:n-3]
	for !utf8.ValidString(s) {
		s = s[:len(s)-1]
	}
	if i := strings.LastIndexByte(s, ' '); i > n/2 {
		s = s[:i]
	}
	return strings.TrimRight(s, " ,;:") + "..."
}

func abbrevBefore(rs []rune) bool {
	w := string(rs)
	if i := strings.LastIndexByte(w, ' '); i >= 0 {
		w = w[i+1:]
	}
	switch strings.ToLower(w) {
	case "e.g", "i.e", "etc", "vs", "mr", "dr", "no", "approx", "т.е", "т.д", "напр":
		return true
	}
	return utf8.RuneCountInString(w) <= 1
}

// pyDocstring returns the module docstring at the top of a Python file.
func pyDocstring(text string) (string, bool) {
	lines := strings.Split(text, "\n")
	i := 0
	for i < len(lines) {
		l := strings.TrimSpace(lines[i])
		if l == "" || strings.HasPrefix(l, "#") {
			i++
			continue
		}
		break
	}
	rest := strings.TrimSpace(strings.Join(lines[i:], "\n"))
	if len(rest) > 0 && strings.ContainsRune("rRuU", rune(rest[0])) {
		rest = rest[1:]
	}
	for _, q := range []string{`"""`, `'''`, `"`, `'`} {
		if strings.HasPrefix(rest, q) {
			body := rest[len(q):]
			if j := strings.Index(body, q); j >= 0 {
				return body[:j], true
			}
			return "", false
		}
	}
	return "", false
}

// goPackageBlocks returns the comment group directly above the package clause.
func goPackageBlocks(text string) []string {
	lines := strings.Split(text, "\n")
	for i, l := range lines {
		if !strings.HasPrefix(l, "package ") {
			continue
		}
		j := i
		for j > 0 && strings.TrimSpace(lines[j-1]) != "" {
			j--
		}
		if j == i {
			return nil
		}
		return commentBlocks(strings.Join(lines[j:i], "\n"), false)
	}
	return nil
}

// headerBlocks returns the comment blocks at the top of the file, before the
// first line of code.
func headerBlocks(text string, hash bool) []string {
	lines := strings.Split(text, "\n")
	end := 0
	inBlock := false
loop:
	for ; end < len(lines); end++ {
		t := strings.TrimSpace(lines[end])
		switch {
		case inBlock:
			if strings.Contains(t, "*/") {
				inBlock = false
			}
		case t == "" || strings.HasPrefix(t, "//") || strings.HasPrefix(t, "#!"):
		case hash && strings.HasPrefix(t, "#"):
		case strings.HasPrefix(t, "/*"):
			if !strings.Contains(t[2:], "*/") {
				inBlock = true
			}
		case isDirective(t):
		default:
			break loop
		}
	}
	return commentBlocks(strings.Join(lines[:end], "\n"), hash)
}

func isDirective(t string) bool {
	t = strings.Trim(t, `;'"`)
	return t == "use strict" || t == "use client" || t == "use server"
}

// commentBlocks splits comment text into blocks (a /* */ comment or a run of
// consecutive line comments) and strips the comment markers.
func commentBlocks(text string, hash bool) []string {
	var blocks, cur []string
	flush := func() {
		if len(cur) > 0 {
			blocks = append(blocks, strings.Join(cur, "\n"))
			cur = nil
		}
	}
	lines := strings.Split(text, "\n")
	for i := 0; i < len(lines); i++ {
		t := strings.TrimSpace(lines[i])
		switch {
		case strings.HasPrefix(t, "/*"):
			flush()
			var body []string
			cur1 := strings.TrimPrefix(strings.TrimPrefix(strings.TrimPrefix(t, "/**"), "/*"), "!")
			if strings.HasPrefix(t, "/**/") {
				cur1 = ""
			}
			for {
				if j := strings.Index(cur1, "*/"); j >= 0 {
					body = append(body, strings.TrimSpace(strings.TrimPrefix(strings.TrimSpace(cur1[:j]), "*")))
					break
				}
				body = append(body, strings.TrimSpace(strings.TrimPrefix(strings.TrimSpace(cur1), "*")))
				i++
				if i >= len(lines) {
					break
				}
				cur1 = lines[i]
			}
			blocks = append(blocks, strings.Join(body, "\n"))
		case strings.HasPrefix(t, "//"):
			l := strings.TrimPrefix(strings.TrimPrefix(t, "//"), "/")
			l = strings.TrimPrefix(l, "!")
			cur = append(cur, strings.TrimSpace(l))
		case hash && strings.HasPrefix(t, "#") && !strings.HasPrefix(t, "#!"):
			cur = append(cur, strings.TrimSpace(strings.TrimLeft(t, "#")))
		default: // blank line or code ends a run of line comments
			flush()
		}
	}
	flush()
	return blocks
}

// archMark matches an `arch:` markup directive at the start of a text or after a space.
var archMark = regexp.MustCompile(`(^|\s)arch:[a-z]`)

// StripArch removes `arch:` markup (arch:flow, arch:step, ...) from a description.
// Markup comments sit next to the prose in the same comment block; their lines
// are not an explanation of the code. Text from the first directive on is cut,
// because the lines of a block may already be joined.
func StripArch(s string) string {
	if loc := archMark.FindStringIndex(s); loc != nil {
		s = s[:loc[0]]
	}
	return strings.TrimSpace(s)
}

// IsArchLine reports whether one comment line is `arch:` markup.
func IsArchLine(l string) bool {
	return strings.HasPrefix(strings.TrimLeft(l, " \t*#/!-"), "arch:")
}

// directiveRe matches tool directives that live in comments but describe
// nothing: linter and formatter switches, compiler pragmas, `arch:` markup.
var directiveRe = regexp.MustCompile(`(?i)^(arch:[a-z]|nolint\b|go:[a-z]|lint:|line \S+:\d|export \w+$|\+build\b|eslint[- ]|prettier-ignore|biome-ignore|deno-lint|@ts-(nocheck|ignore|check|expect-error)|istanbul |c8 ignore|pylint:|noqa\b|type:\s*ignore|mypy:|isort:|fmt:\s*(off|on|skip)|swiftlint:|ktlint|noinspection|nosonar|revive:|#?nosec\b|gosec\b|staticcheck\b|lint-ignore|#?(end)?region\b|mark:\s*-?|pragma\b)`)

// IsDirectiveLine reports whether one comment line (with or without the comment
// marker) is a tool directive (`//nolint`, `//go:generate`, `# noqa`,
// `// eslint-disable`, `arch:` markup, ...) rather than prose.
func IsDirectiveLine(l string) bool {
	return directiveRe.MatchString(strings.TrimSpace(strings.TrimLeft(l, " \t*#/!-")))
}

// Summary cleans a comment block written as a description (a proto comment,
// an actor description): directive lines are dropped, the first paragraph is
// joined and cut to its first sentences (Shorten). Unlike Describe, short
// texts ("Меню ресторана") are kept.
func Summary(raw string) string {
	var keep []string
	for _, l := range strings.Split(raw, "\n") {
		l = strings.TrimSpace(strings.TrimLeft(strings.TrimSpace(l), "*#/!"))
		if IsDirectiveLine(l) || decoRe.MatchString(l) && strings.Trim(l, "-=*_~# ") == "" {
			continue
		}
		if l == "" {
			if len(keep) > 0 {
				break
			}
			continue
		}
		keep = append(keep, l)
	}
	return Shorten(strings.Join(keep, " "))
}
